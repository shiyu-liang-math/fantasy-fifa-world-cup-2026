const structureBytes = readFileSync(structurePath);
const structure = JSON.parse(structureBytes);
const results = JSON.parse(readFileSync(resultsPath, "utf8"));
const structureSha256 = createHash("sha256")
  .update(structureBytes)
  .digest("hex");

if (structureSha256 !== results.structureSha256) {
  throw new Error(
    `Official results target structure ${results.structureSha256}, but the file hash is ${structureSha256}.`,
  );
}

